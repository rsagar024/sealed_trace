// Generates reference vectors with Node's crypto, which is an independent
// implementation from the Dart code under test.
//
//   node tool/generate_vectors/generate_node_vectors.js
//
// Writes test/vectors/aes_gcm_node_vectors.json and
// test/vectors/rsa_oaep_node_vectors.json. Random inputs come from a seeded
// generator so the files are reproducible; the RSA-OAEP ciphertexts are
// randomized by Node and so change on every run.
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const outDir = path.join(__dirname, '..', '..', 'test', 'vectors');

// Small deterministic generator (xorshift32) so fixtures are reproducible.
let state = 0x1badf00d;
function nextByte() {
  state ^= state << 13; state >>>= 0;
  state ^= state >>> 17;
  state ^= state << 5; state >>>= 0;
  return state & 0xff;
}
const bytes = (n) => Buffer.from(Array.from({ length: n }, nextByte));
const b64 = (b) => b.toString('base64');

// ---- AES-256 single blocks (ECB, no padding) ----
const blockCases = [];
// FIPS-197 appendix C.3 AES-256 example.
blockCases.push({
  name: 'fips197-c3',
  keyBase64: b64(Buffer.from(Array.from({ length: 32 }, (_, i) => i))),
  plaintextBase64: b64(Buffer.from('00112233445566778899aabbccddeeff', 'hex')),
});
for (let i = 0; i < 40; i++) {
  blockCases.push({ name: `random-${i}`, keyBase64: b64(bytes(32)), plaintextBase64: b64(bytes(16)) });
}
for (const c of blockCases) {
  const cipher = crypto.createCipheriv('aes-256-ecb', Buffer.from(c.keyBase64, 'base64'), null);
  cipher.setAutoPadding(false);
  c.ciphertextBase64 = b64(Buffer.concat([cipher.update(Buffer.from(c.plaintextBase64, 'base64')), cipher.final()]));
}

// ---- AES-256-GCM ----
function gcm(name, key, iv, plaintext, aad) {
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  if (aad.length) cipher.setAAD(aad);
  const ct = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  return {
    name,
    keyBase64: b64(key),
    ivBase64: b64(iv),
    aadBase64: b64(aad),
    plaintextBase64: b64(plaintext),
    ciphertextBase64: b64(ct),
    tagBase64: b64(cipher.getAuthTag()),
  };
}

const gcmCases = [];
const zeroKey = Buffer.alloc(32);
const zeroIv = Buffer.alloc(12);
// McGrew-Viega GCM test cases 13 and 14 (256-bit key, zero key and IV).
gcmCases.push(gcm('nist-tc13-empty', zeroKey, zeroIv, Buffer.alloc(0), Buffer.alloc(0)));
gcmCases.push(gcm('nist-tc14-one-zero-block', zeroKey, zeroIv, Buffer.alloc(16), Buffer.alloc(0)));
// Test cases 15 and 16 (shared key, IV, plaintext; 16 adds AAD and a short tail).
const k15 = Buffer.from('feffe9928665731c6d6a8f9467308308feffe9928665731c6d6a8f9467308308', 'hex');
const iv15 = Buffer.from('cafebabefacedbaddecaf888', 'hex');
const pt15 = Buffer.from(
  'd9313225f88406e5a55909c5aff5269a86a7a9531534f7da2e4c303d8a318a72' +
  '1c3c0c95956809532fcf0e2449a6b525b16aedf5aa0de657ba637b391aafd255', 'hex');
const aad16 = Buffer.from('feedfacedeadbeeffeedfacedeadbeefabaddad2', 'hex');
gcmCases.push(gcm('nist-tc15-four-blocks', k15, iv15, pt15, Buffer.alloc(0)));
gcmCases.push(gcm('nist-tc16-with-aad-and-tail', k15, iv15, pt15.subarray(0, 60), aad16));

for (const n of [1, 2, 3, 7, 8, 15, 16, 17, 31, 32, 33, 47, 48, 49, 63, 64, 65, 100, 127, 128, 129, 255, 256, 300]) {
  gcmCases.push(gcm(`random-len-${n}`, bytes(32), bytes(12), bytes(n), Buffer.alloc(0)));
}
for (const n of [0, 1, 15, 16, 17, 40]) {
  gcmCases.push(gcm(`random-aad-${n}`, bytes(32), bytes(12), bytes(50), bytes(n)));
}
for (const n of [4096, 10000, 100000]) {
  gcmCases.push(gcm(`random-len-${n}`, bytes(32), bytes(12), bytes(n), Buffer.alloc(0)));
}

fs.writeFileSync(
  path.join(outDir, 'aes_gcm_node_vectors.json'),
  JSON.stringify({
    description: [
      'Reference vectors generated by Node crypto (tool/generate_vectors/generate_node_vectors.js).',
      'blockCases: AES-256 single block, no padding. gcmCases: AES-256-GCM with a 12-byte IV and a 16-byte tag.',
      'nist-tc13..16 are the McGrew-Viega GCM test cases for 256-bit keys, recomputed by Node.',
    ],
    blockCases,
    gcmCases,
  }, null, 1) + '\n',
);

// ---- RSA-OAEP (SHA-256, MGF1-SHA-256, empty label) produced by Node ----
const privatePem = fs.readFileSync(path.join(outDir, 'envelope_vectors.json'), 'utf8');
const keys = JSON.parse(privatePem).testOnlyKeys;
const publicKey = crypto.createPublicKey(keys.publicKeySpki);
const oaepCases = [];
for (const len of [0, 1, 16, 32, 33, 100, 190]) {
  const message = bytes(len);
  const ct = crypto.publicEncrypt(
    { key: publicKey, padding: crypto.constants.RSA_PKCS1_OAEP_PADDING, oaepHash: 'sha256' },
    message,
  );
  oaepCases.push({ name: `node-encrypted-${len}-bytes`, messageBase64: b64(message), ciphertextBase64: b64(ct) });
}

fs.writeFileSync(
  path.join(outDir, 'rsa_oaep_node_vectors.json'),
  JSON.stringify({
    description: [
      'RSA-OAEP ciphertexts produced by Node (SHA-256 label hash, MGF1-SHA-256, empty label) for the test-only key',
      'in envelope_vectors.json. The Dart test decoder must recover messageBase64 from each ciphertextBase64.',
      'OAEP is randomized, so these ciphertexts change every time this script runs.',
    ],
    oaepCases,
  }, null, 1) + '\n',
);

console.log(`wrote ${blockCases.length} block, ${gcmCases.length} GCM, ${oaepCases.length} OAEP cases`);
