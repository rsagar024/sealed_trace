// ignore_for_file: avoid_print
// Line-coverage gate for the core of the SDK (P9.1).
//
//   flutter test --coverage
//   dart run tool/coverage/check_coverage.dart [coverage/lcov.info] [--min=90]
//
// Reads the lcov file that `flutter test --coverage` writes, prints a table
// per file, and exits with code 1 if the core total is below the minimum.
// Core is everything the SDK runs on the device except the facade glue and
// models. Files that only run in a browser or are generated are listed but
// not counted, because the VM suite cannot execute them (the browser parts are
// covered by tool/web_check instead).

import 'dart:io';

/// Directories under lib/src that make up the core.
const coreDirs = [
  'masking',
  'queue',
  'crypto',
  'storage',
  'upload',
  'network',
  'event',
  'transport',
];

/// Files that the VM suite cannot run (or that never execute), and why.
const excluded = {
  'lib/src/storage/database.g.dart': 'generated by drift_dev',
  'lib/src/storage/database.dart':
      'drift table declarations, read by the code generator, not executed',
  'lib/src/storage/open_storage_stub.dart': 'platforms with neither io nor web',
  'lib/src/storage/indexeddb_storage_adapter.dart': 'browser only',
  'lib/src/storage/open_storage_web.dart': 'browser only',
  'lib/src/storage/envelope_spill_web.dart': 'browser only',
};

void main(List<String> args) {
  final path = args.firstWhere(
    (a) => !a.startsWith('--'),
    orElse: () => 'coverage/lcov.info',
  );
  final minArg = args.firstWhere(
    (a) => a.startsWith('--min='),
    orElse: () => '--min=90',
  );
  final minimum = double.parse(minArg.substring(6));

  final file = File(path);
  if (!file.existsSync()) {
    stderr.writeln('No $path. Run `flutter test --coverage` first.');
    exit(2);
  }

  // lcov: SF:<file>, DA:<line>,<hits>, end_of_record.
  final hit = <String, int>{};
  final found = <String, int>{};
  String? current;
  for (final line in file.readAsLinesSync()) {
    if (line.startsWith('SF:')) {
      current = line.substring(3).replaceAll(r'\', '/');
      final i = current.indexOf('lib/');
      if (i > 0) current = current.substring(i);
      hit.putIfAbsent(current, () => 0);
      found.putIfAbsent(current, () => 0);
    } else if (line.startsWith('DA:') && current != null) {
      final hits = int.parse(line.substring(3).split(',')[1]);
      found[current] = found[current]! + 1;
      if (hits > 0) hit[current] = hit[current]! + 1;
    }
  }

  // Files never loaded by any test do not appear in lcov at all.
  final libFiles = Directory('lib/src')
      .listSync(recursive: true)
      .whereType<File>()
      .map((f) => f.path.replaceAll(r'\', '/'))
      .where((p) => p.endsWith('.dart'))
      .map((p) => p.substring(p.indexOf('lib/')))
      .toList();

  bool isCore(String p) => coreDirs.any((d) => p.startsWith('lib/src/$d/'));

  var coreHit = 0;
  var coreFound = 0;
  final rows = <String>[];
  final missing = <String>[];
  for (final p in libFiles.where(isCore).toList()..sort()) {
    if (excluded.containsKey(p)) {
      rows.add('  ${'excluded'.padLeft(8)}  $p (${excluded[p]})');
      continue;
    }
    final f = found[p];
    if (f == null) {
      // lcov leaves out files without executable lines (constants, enums,
      // exports). A file with a function body that no test loads is a gap.
      final body = File(p).readAsStringSync();
      final hasCode = RegExp(r'\)\s*(async\s*)?(\{|=>)').hasMatch(body);
      if (hasCode) missing.add(p);
      rows.add('  ${(hasCode ? 'NOT RUN' : 'no code').padLeft(8)}  $p');
      continue;
    }
    if (f == 0) continue; // No executable lines (pure declarations).
    coreHit += hit[p]!;
    coreFound += f;
    final pct = 100 * hit[p]! / f;
    rows.add('  ${pct.toStringAsFixed(1).padLeft(7)}%  $p (${hit[p]}/$f)');
  }

  var allHit = 0;
  var allFound = 0;
  for (final p in found.keys) {
    if (excluded.containsKey(p)) continue;
    allHit += hit[p]!;
    allFound += found[p]!;
  }

  print('Core line coverage by file:');
  rows.forEach(print);
  final core = coreFound == 0 ? 0.0 : 100 * coreHit / coreFound;
  final all = allFound == 0 ? 0.0 : 100 * allHit / allFound;
  print('');
  print('Core:     ${core.toStringAsFixed(2)}% ($coreHit/$coreFound lines)');
  print('All lib:  ${all.toStringAsFixed(2)}% ($allHit/$allFound lines)');
  if (missing.isNotEmpty) {
    print('Core files with code that no test loaded: ${missing.join(', ')}');
  }
  if (core < minimum || missing.isNotEmpty) {
    print('FAIL: core coverage below $minimum% or files not loaded');
    exit(1);
  }
  print('OK: core coverage at or above $minimum%');
}
